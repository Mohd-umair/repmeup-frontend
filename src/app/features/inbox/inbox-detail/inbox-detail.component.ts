  ngOnInit(): void {
    this.currentUser = this.authService.currentUserValue;
    this.loadAvailableAgents();
  }

  ngOnChanges(changes: SimpleChanges): void {
    if (changes['interaction']) {
      const prev: IInteraction | null = changes['interaction'].previousValue;
      const next: IInteraction | null = changes['interaction'].currentValue;
      const isSameConversation = prev && next && prev._id === next._id;

      if (!changes['interaction'].firstChange) {
        this.clearAISuggestion();

        if (!isSameConversation) {
          // Switched to a different conversation — reset everything
          this.replyForm.reset();
          this.resetReplyTextareaHeight();
          this.pendingAttachment = null;
          this.stopRecordingStream();
          this.optimisticReplies = [];
          this.visibleTimelineCount = this.timelinePageSize;
        } else if (next?.replies?.length) {
          // Same conversation refreshed — drop optimistic entries that now
          // exist as confirmed replies in the server response
          this.optimisticReplies = this.optimisticReplies.filter(opt =>
            !next.replies!.some(r => !r.isPlatformReply && r.content === opt.content)
          );
        }
        this.updateTimeline();
      }

      // Scroll to the latest message only when conversation changes or new content arrived
      if (next) {
        if (!isSameConversation) {
          this.scheduleScrollToBottom('instant');
        } else {
          // Same conversation: only scroll if there is actually new content (replies or incoming messages)
          const prevReplies = prev?.replies?.length ?? 0;
          const nextReplies = next.replies?.length ?? 0;
          const prevIncoming = (prev as any)?.metadata?.incomingMessages?.length ?? 0;
          const nextIncoming = (next as any)?.metadata?.incomingMessages?.length ?? 0;
          const hasNewContent = nextReplies > prevReplies || nextIncoming > prevIncoming;
          if (hasNewContent) {
            this.scheduleScrollToBottom('smooth');
          }
        }
      }

      // Mark notifications as read when the conversation is viewed.
      // NOTE: marking the interaction itself as 'read' is handled exclusively
      // in onInteractionSelect() (the container), so we never override a
      // manually-set 'unread' status from a background lifecycle event.
      if (this.interaction && this.interaction._id) {
        this.markNotificationsAsRead();
      }

      this.updateTimeline();
    }
  }

  /** Recompute and assign cached timeline (call when interaction or optimisticReplies change only) */
  private updateTimeline(): void {
    this.conversationTimeline = this.getConversationTimeline();
    this.updateVisibleTimeline();
  }

  ngOnDestroy(): void {
    this.timedTasks.unsubscribe();
    this.stopRecordingStream();
    this.subscriptions.forEach(sub => sub.unsubscribe());
  }

