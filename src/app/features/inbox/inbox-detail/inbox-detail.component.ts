  /** Observable DM attachment image URL (Facebook: fetched via proxy with auth). */
  /** True when content is the placeholder we use for image-only messages (don't show under the image). */
  isImagePlaceholder(content: string | undefined): boolean {
    if (!content || typeof content !== 'string') return false;
    const t = content.trim();
    return t === '[image]' || t === '[attachment]';
  }

  getAttachmentUrl$(interactionId: string, mid: string, platform: string, directUrl: string | undefined): Observable<SafeUrl | null> {
    if ((platform === 'facebook' || platform === 'instagram') && interactionId && mid) {
      return this.avatarService.getAttachmentUrl(interactionId, mid).pipe(
        map(url => (url ? this.sanitizer.bypassSecurityTrustUrl(url) : null))
      );
    }
    return of(directUrl ? this.sanitizer.bypassSecurityTrustUrl(directUrl) : null);
  }

  /** Display name with platform fallback when profile isn't available (e.g. Instagram without Advanced Access). */
  getAuthorDisplayName(obj: { author?: IInteraction['author']; platform?: string } | null): string {
    if (!obj) return 'Unknown';
    const name = obj.author?.name || obj.author?.username;
    if (name) return name;
    if (obj.platform === 'instagram') return 'Instagram User';
    if (obj.platform === 'facebook') return 'Messenger User';
    return 'Unknown';
  }

  getPlatformColors(): any {
    if (!this.interaction) return null;
    const theme = this.themeService.getTheme(this.interaction.platform);
    return {
      primary: theme.primaryColor,
      secondary: theme.secondaryColor,
      gradientFrom: theme.gradientFrom,
      gradientTo: theme.gradientTo
    };
  }

  submitReply(): void {
    if (!this.interaction) return;

    const content = (this.replyForm.value.content || '').trim();
    const hasAttachment = !!this.pendingAttachment;
    if (!content && !hasAttachment) return;

    // Capture attachment before clearing (used for API and optimistic display)
    const attachmentUrl = this.pendingAttachment?.publicUrl;
    const attachmentType = this.pendingAttachment?.mediaType;
    const caption = content;

    // ── 1. Inject optimistic reply immediately ───────────────────────────────
    const displayContent = caption || (hasAttachment ? `[${attachmentType}]` : '');
    const optimistic: IOptimisticReply = {
      _optimistic: true,
      content: displayContent,
      sentAt: new Date(),
      sentBy: this.currentUser,
      status: 'pending',
      isPlatformReply: false,
      wasAutoGenerated: false,
      ...(attachmentUrl && attachmentType && { attachmentUrl, attachmentType })
    };
    this.optimisticReplies = [...this.optimisticReplies, optimistic];
    this.updateTimeline();
    this.replyForm.reset();
    this.resetReplyTextareaHeight();
    this.pendingAttachment = null;
    this.submittingReply = true;
    this.replySuccess = false;
    this.scheduleScrollToBottom('instant');

    // ── 2. Send to backend (caption + optional attachment) ─────────────────
    this.inboxService.replyToInteraction(
      this.interaction._id,
      caption,
      undefined,
      undefined,
      attachmentUrl,
      attachmentType
    ).subscribe({
      next: (response) => {
        this.submittingReply = false;
        if (response.success) {
          optimistic.status = 'sent' as any;
          this.optimisticReplies = [...this.optimisticReplies];
          this.updateTimeline();
          this.replySuccess = true;
          this.interactionUpdate.emit();
          this.timedTasks.add(
            timer(3000)
              .pipe(take(1))
              .subscribe(() => {
                this.replySuccess = false;
              })
          );
        } else {
          optimistic.status = 'failed';
          this.optimisticReplies = [...this.optimisticReplies];
          this.updateTimeline();
          const msg = (response as any).error || 'Reply could not be sent to the platform.';
          this.sweetAlertService.toast('error', msg);
          this.cdr.markForCheck();
        }
      },
      error: (err) => {
        optimistic.status = 'failed';
        this.optimisticReplies = [...this.optimisticReplies];
        this.updateTimeline();
        this.submittingReply = false;
        const msg = err?.error?.error || err?.error?.message || err?.message || 'Reply could not be sent. Check your connection and platform settings.';
        this.sweetAlertService.toast('error', msg);
        this.cdr.markForCheck();
      }
    });
  }

  onReplyTextareaKeydown(event: KeyboardEvent): void {
    // Enter sends message, Shift+Enter keeps newline behavior.
    if (event.key !== 'Enter' || event.shiftKey || event.isComposing) {
      return;
    }

    event.preventDefault();

    if (this.submittingReply) return;
    const content = (this.replyForm.value.content || '').trim();
    const hasAttachment = !!this.pendingAttachment;
    if (!content && !hasAttachment) return;

    this.submitReply();
  }

