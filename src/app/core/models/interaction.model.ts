export interface IInteraction {
  _id: string;
  organization: string;
  platform: Platform;
  type: InteractionType;
  platformId: string;
  platformUrl?: string;
  content: string;
  author: IAuthor;
  status: InteractionStatus;
  sentiment?: Sentiment;
  sentimentScore?: number;
  sentimentConfidence?: number;
  topics?: string[];
  intent?: string;
  urgency?: Urgency;
  aiSuggestion?: IAISuggestion;
  autoReplyEligible?: boolean;
  autoReplied?: boolean;
  assignedTo?: string;
  assignedBy?: string;
  assignedAt?: Date;
  assignmentReason?: string;
  assignmentHistory?: IAssignmentHistory[];
  intentBucket?: any;
  bucketAssignedBy?: 'keyword' | 'ai' | 'manual';
  labels?: ILabel[];
  priority?: Priority;
  tags?: string[];
  /** Star rating (1–5) for review-type interactions (e.g. Google Business) */
  rating?: number;
  metadata?: any;
  replies?: IReply[];
  responseCount?: number;
  internalNotes?: INote[];
  engagement?: IEngagement;
  platformCreatedAt: Date;
  respondedAt?: Date;
  resolvedAt?: Date;
  createdAt: Date;
  updatedAt: Date;
  /** When false, conversation is treated as closed in inbox filters until reopened */
  chatOpen?: boolean;
  /** Linked unified contact ID (resolved from author identity) */
  contact?: string | null;
  /** Chat summary — written manually or generated by AI */
  summary?: string | null;
  /** Suggested next action from AI (only set on AI-generated summaries) */
  summarySuggestedAction?: string | null;
  summaryGeneratedAt?: Date;
  summaryGeneratedBy?: 'ai' | 'manual' | null;
  /** Support desk ticket number (sequential per org, starts at 101) */
  chatNumber?: number;
  /** Formatted ticket reference e.g. #REP-101 */
  chatRef?: string;
}

