export interface IReply {
  _id: string;
  content: string;
  sentBy: string | IReplyUser;
  sentAt: Date;
  platformResponseId?: string;
  wasAutoGenerated?: boolean;
  /** AI confidence score (0–1). Only set on auto-generated replies. */
  confidence?: number | null;
  /** AI-detected message type (small_talk, closing, business, unclear). */
  messageType?: string | null;
  status?: 'sent' | 'failed' | 'deleted' | 'received' | 'pending';
  /** Attachment sent with this reply (image/video/file) */
  attachmentUrl?: string;
  attachmentType?: 'image' | 'video' | 'file' | 'audio';

  // Platform reply fields (for replies from other users on YouTube/Instagram/etc)
  isPlatformReply?: boolean; // True if this is a reply from the platform, false if from app
  platform?: string; // youtube, instagram, facebook, google
  platformId?: string; // Platform-specific ID
  author?: {
    platformId?: string;
    name?: string;
    username?: string;
    profileUrl?: string;
    avatarUrl?: string;
    isVerified?: boolean;
  };
  sentiment?: 'positive' | 'negative' | 'neutral';
  platformUrl?: string;
}

